#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn trid_is_its_own_inverse() {
        for v in [[0u8, 0, 0], [1, 2, 3], [255, 128, 7], [0x9b, 0x02, 0xed]] {
            assert_eq!(trid_inv(trid(v)), v, "trid round trip {v:?}");
        }
    }

    #[test]
    fn identity_encrypt_decrypt_round_trips() {
        let c = [0x11u8, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88];
        for ssi in [0u32, 1, 0x00_1234, 0x12_3456, 0xff_ffff] {
            let esi = encrypt_id(&c, ssi);
            assert_eq!(decrypt_id(&c, esi), ssi, "ssi {ssi:#08x}");
        }
    }

    /// Recover `c` from three (SSI, ESI) pairs, searching a window that
    /// contains the true guess. The full attack sweeps 0..1<<40; the window
    /// keeps the test quick while running the real meet-in-the-middle.
    #[test]
    fn recovers_c_from_three_pairs() {
        // A c whose five guessed bytes (c0,c2,c3,c5,c6) pack to a small
        // number, so a narrow window reaches it fast.
        let c = [0x03u8, 0x11, 0x02, 0x00, 0x77, 0x01, 0x00, 0x88];
        let ssis = [0x12_3456u32, 0x00_4321, 0xab_cdef];
        let pairs: Vec<IdPair> =
            ssis.iter().map(|&ssi| IdPair { ssi, esi: encrypt_id(&c, ssi) }).collect();

        // Guess packs c0 | c2<<8 | c3<<16 | c5<<24 | c6<<32
        // = 03 | 02<<8 | 00<<16 | 01<<24 | 00<<32 = 0x0100_0203.
        let g = 0x0100_0203u64;
        let hits = recover_c_range(&pairs, g - 4..g + 4);
        assert!(hits.contains(&c), "recovered the true c: {hits:02x?}");
        assert_eq!(hits.len(), 1, "three pairs leave one candidate in the window");

        // And the recovered c decrypts every ESI back to its SSI.
        for p in &pairs {
            assert_eq!(decrypt_id(&hits[0], p.esi), p.ssi);
        }
    }
}
