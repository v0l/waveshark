/// The 49 bits XORed over an AMBE frame's data bits under key number `k`,
/// laid out as the decoder lays them: C0's twelve data bits, C1's twelve,
/// C2's eleven, C3's fourteen. The last bit is never touched.
///
/// `None` for key number zero, which is no key.
pub fn keystream(k: u8) -> Option<[bool; 49]> {
    if k == 0 {
        return None;
    }
    let v = u64::from(BPK[k as usize]);
    let bits: u64 = ((v & 0xff0f) << 32) | (v << 16) | v;
    let mut out = [false; 49];
    for (j, b) in out.iter_mut().take(48).enumerate() {
        *b = (bits >> (47 - j)) & 1 == 1;
    }
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Key 1 is the pattern the DSD-FME table gives it, laid out as its
    /// decoder lays it: the 16-bit value with its middle byte masked, then
    /// the value twice.
    #[test]
    fn key_one_is_the_table_entry_repeated() {
        let ks = keystream(1).unwrap();
        let word = |from: usize| ks[from..from + 16].iter().fold(0u16, |a, &b| (a << 1) | u16::from(b));
        assert_eq!(word(16), 0x1f00);
        assert_eq!(word(32), 0x1f00);
        assert_eq!(word(0), 0x1f00 & 0xff0f);
        assert!(!ks[48]);
        assert!(keystream(0).is_none());
    }
}
