/// Returns the synthesis window coefficient for index `n`, zero outside
/// -105 to 105.
pub fn synthesis_window(n: i32) -> f32 {
    if !(-105..=105).contains(&n) {
        return 0.0;
    }
    SYNTHESIS[(n + 105) as usize]
}

/// Returns the pitch refinement window coefficient for index `n`, zero
/// outside -110 to 110.
pub fn pitch_refinement_window(n: i32) -> f32 {
    if !(-110..=110).contains(&n) {
        return 0.0;
    }
    PITCH_REFINEMENT[(n + 110) as usize]
}
